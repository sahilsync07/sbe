export const COLOR_KEYS = Object.keys(COLOR_MAP).sort((a, b) => b.length - a.length);

/**
 * Multi-word phrases that should be checked before single tokens
 */
const MULTI_WORD_COLORS = [
    'FULL WHITE', 'FULL BLACK', 'FULL-WHITE', 'FULL-BLACK',
    'FOREST GREEN', 'ROYAL BLUE', 'PEACOCK BLUE', 'DEEP CYAN',
    'LIGHT GREY', 'DARK GREY', 'LIGHT PINK', 'BABY PINK',
    'SAGE GREEN', 'OLIVE GREEN', 'NAVY BLUE', 'MILITARY GREEN',
    'TEAL BLUE', 'F GREEN'
];

/**
 * Smartly extract color information from a product name.
 * Handles abbreviations, two-tone pair colors (e.g. WHT-BLK, BLK/RED),
 * compound codes (BRB, BRT, BNR), stuck punctuation, and strict domain negative rules.
 *
 * @param {string} productName - The full raw product name
 * @returns {{ text: string, hex: string, hex2?: string, gradient?: string, originalTokens: string[] } | null}
 */
export function extractColor(productName) {
    if (!productName) return null;

    let str = productName.toUpperCase().trim();

    // 1. Domain negative exclusions:
    // "MGT BLUE": article name in Magnet brand, NOT color blue!
    if (/\bMGT\s+BLUE\b/i.test(str)) {
        str = str.replace(/\bMGT\s+BLUE\b/gi, 'MGT_ARTICLE');
    }

    // "POLO": article name, NOT a color (e.g. DUROLITE POLO 2, ACTION POLO BLK, SWASTIK KIDS POLO)
    str = str.replace(/\bPOLO\b/gi, '');

    // Ignore P-TOES / PTOES brand prefix (avoid confusing with Peacock)
    str = str.replace(/\bP[\s\-\.]*TOES\b/gi, '');

    // Ignore MERRY GOLD / MARY GOLD / SPORTS-GOLD article names
    str = str.replace(/\b(MERRY|MARY|SPORTS)[\s\-]+GOLD\b/gi, '$1_MODEL');

    // 2. Pre-process stuck punctuation:
    // Disconnect trailing discount percentages from colors: e.g. BRN-40% -> BRN 40%
    str = str.replace(/([A-Z\.]+)-+(\d+%)/gi, '$1 $2');

    // Disconnect prices and slashes from colors: e.g. MRP279/-BRN -> MRP279/- BRN
    str = str.replace(/(\/[-–—]?)\s*([A-Za-z])/g, '$1 $2');

    // Disconnect closing brackets from colors: e.g. (6X9)BRN -> (6X9) BRN
    str = str.replace(/([\)\]])\s*([A-Za-z])/g, '$1 $2');

    // Disconnect opening brackets from colors: e.g. BRN(6X9) -> BRN (6X9)
    str = str.replace(/([A-Za-z])\s*([\(\[])/g, '$1 $2');

    // Disconnect colors stuck to digits: e.g. 7*10wht -> 7*10 wht, 11*13Wht -> 11*13 wht
    str = str.replace(/(\d+)\s*(WHT|BLK|BRN|GRY|BLU|RED|PNK|GLD)\b/gi, '$1 $2');

    // 3. PAIR MATCHING: Check for slash or hyphen color pairs (e.g. WHT-BLK, WHT/BLK, BLK/RED, D.GRY/ORANGE)
    const pairRegex = /\b([A-Z0-9\.]+)\s*[\/\-]\s*([A-Z0-9\.]+)\b/g;
    let pairMatch;
    while ((pairMatch = pairRegex.exec(str)) !== null) {
        const t1 = pairMatch[1];
        const t2 = pairMatch[2];
        const c1 = COLOR_MAP[t1];
        const c2 = COLOR_MAP[t2];

        // Valid color pair requires BOTH parts to be known colors
        if (c1 && c2 && t1 !== t2) {
            const wholePair = pairMatch[0];
            const primaryColor = c1.color;
            const secondaryColor = c2.color;
            return {
                text: `${c1.label} & ${c2.label}`,
                hex: primaryColor,
                hex2: secondaryColor,
                gradient: `linear-gradient(135deg, ${primaryColor} 50%, ${secondaryColor} 50%)`,
                originalTokens: [wholePair, t1, t2]
            };
        }
    }

    // 4. MULTI-WORD COLOR CHECK (e.g. FULL WHITE, FULL BLACK, FOREST GREEN, ROYAL BLUE, etc.)
    for (const phrase of MULTI_WORD_COLORS) {
        const safePhrase = phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const phraseRegex = new RegExp(`(^|[^a-zA-Z0-9])${safePhrase}(?=[^a-zA-Z0-9]|$)`, 'i');
        if (phraseRegex.test(str)) {
            const data = COLOR_MAP[phrase];
            if (data) {
                return {
                    text: data.label,
                    hex: data.color,
                    hex2: data.color2 || null,
                    gradient: data.gradient || null,
                    originalTokens: [phrase]
                };
            }
        }
    }

    // 5. TOKEN MATCHING: Split keeping dotted tokens intact (e.g. D.GRY, F.GRN, P.COCK, T.BLU)
    const tokens = str.split(/[\s\(\)\[\],]+/).filter(Boolean);
    const foundTokens = [];
    const foundData = [];

    for (let i = 0; i < tokens.length; i++) {
        let token = tokens[i].trim();
        // Remove trailing or leading punctuation like /- or :
        token = token.replace(/^[\/\-\:\.]+|[\/\-\:\.]+$/g, '');
        if (!token) continue;

        // Skip single-letter P
        if (token === 'P') continue;

        const data = COLOR_MAP[token];
        if (data) {
            foundTokens.push(token);
            foundData.push(data);
        }
    }

    if (foundTokens.length === 0) {
        return null;
    }

    if (foundTokens.length === 1) {
        const d = foundData[0];
        return {
            text: d.label,
            hex: d.color,
            hex2: d.color2 || null,
            gradient: d.gradient || null,
            originalTokens: [foundTokens[0]]
        };
    }

    // Multiple distinct tokens found (e.g. ACTION RIDE BLK BRN -> Black & Brown)
    const uniqueLabels = [...new Set(foundData.map(d => d.label))];
    const d1 = foundData[0];
    const d2 = foundData[1];
    const primaryColor = d1.color;
    const secondaryColor = d2.color;

    return {
        text: uniqueLabels.join(' & '),
        hex: primaryColor,
        hex2: secondaryColor,
        gradient: `linear-gradient(135deg, ${primaryColor} 50%, ${secondaryColor} 50%)`,
        originalTokens: [...new Set(foundTokens)]
    };
}
